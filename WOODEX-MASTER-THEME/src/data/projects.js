export const featuredProjects = (limit) => {
  const list = projects.filter((p) => p.featured);
  return limit ? list.slice(0, limit) : list;
};

export const sectorLabel = (id) => sectors.find((s) => s.id === id)?.label ?? id;
export const getProject = (slug) => projects.find((p) => p.slug === slug);
export const projectsBySector = (sector) => projects.filter((p) => p.sector === sector);
export const projectNeighbours = (slug) => {
  const i = projects.findIndex((p) => p.slug === slug);
  return {
    prev: i > 0 ? projects[i - 1] : projects[projects.length - 1],
    next: i < projects.length - 1 ? projects[i + 1] : projects[0],
  };
};

export default projects;
